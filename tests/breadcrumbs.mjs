import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { PrismaClient } from '@prisma/local-client';
import bcrypt from 'bcryptjs';
const require = createRequire(import.meta.url), path = process.env.PLAYWRIGHT_MODULE_PATH ?? 'playwright';
const { chromium } = require(path), { expect } = require(path + '/test');
const base = process.env.TEST_BASE_URL ?? 'http://127.0.0.1:3188';
assert.ok(['localhost', '127.0.0.1'].includes(new URL(base).hostname));
assert.ok(process.env.TEST_DATABASE_URL?.startsWith('file:/private/tmp/'));
const db = new PrismaClient({ datasources: { db: { url: process.env.TEST_DATABASE_URL } } });
let farm, user, browser;
try {
  const suffix = Date.now();
  farm = await db.farm.create({ data: { name: 'Breadcrumb fixture', code: `crumbs-${suffix}` } });
  user = await db.user.create({ data: { name: 'Breadcrumb Manager', email: `crumbs-${suffix}@example.test`, password: await bcrypt.hash('Breadcrumb-test-123', 10), emailVerifiedAt: new Date() } });
  await db.farmMember.create({ data: { userId: user.id, farmId: farm.id, role: 'MANAGER' } });
  const name = 'Thunder with a very long registered name for responsive breadcrumb verification';
  const horse = await db.horse.create({ data: { farmId: farm.id, name } });
  browser = await chromium.launch({ headless: true, ...(process.env.TEST_CHROME_PATH ? { executablePath: process.env.TEST_CHROME_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  assert.equal((await context.request.post(base + '/api/auth/login', { headers: { origin: base }, data: { email: user.email, password: 'Breadcrumb-test-123' } })).status(), 200);
  await context.addCookies([{ name: 'reinwell_farm', value: farm.id, url: base }]);
  const page = await context.newPage();
  await page.goto(base + `/horses/${horse.id}/edit`);
  const nav = page.getByRole('navigation', { name: 'Breadcrumb', exact: true });
  await expect(nav).toBeVisible();
  await expect(nav.getByRole('listitem')).toHaveCount(3);
  await expect(nav.locator('[aria-current=page]')).toHaveText('Edit profile');
  assert.equal(await nav.locator('[aria-current=page]').evaluate(el => el.tagName), 'SPAN');
  await expect(nav.getByRole('link', { name, exact: true })).toHaveAttribute('href', `/horses/${horse.id}`);
  await expect(nav.getByRole('link', { name, exact: true })).toHaveAttribute('title', name);
  assert.ok(await nav.getByRole('link', { name, exact: true }).evaluate(el => el.scrollWidth > el.clientWidth), 'Long ancestor label truncates');
  assert.ok(await nav.evaluate(el => el.getBoundingClientRect().right <= window.innerWidth), 'Breadcrumb fits phone viewport');
  await page.getByLabel('Name', { exact: true }).fill('Unsaved breadcrumb edit');
  await nav.getByRole('link', { name: 'Horses', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Discard profile changes?' })).toBeVisible();
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Unsaved breadcrumb edit');
  await nav.getByRole('link', { name, exact: true }).click();
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
  await expect(page.getByRole('heading', { name, exact: true, level: 1 })).toBeVisible();
  await expect(nav.getByRole('listitem')).toHaveCount(2);
  await expect(nav.locator('[aria-current=page]')).toHaveText(name);
  await nav.getByRole('link', { name: 'Horses', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your horses', exact: true })).toBeVisible();
  await expect(nav).toHaveCount(0);
  console.log('PASS: real horse hierarchy, nonlinked current page, phone truncation/full labels, clickable ancestors, unsaved-edit guard, and no breadcrumbs on shallow directory');
} finally {
  await browser?.close(); if (farm) await db.farm.delete({ where: { id: farm.id } }); if (user) await db.user.delete({ where: { id: user.id } }); await db.$disconnect();
}
