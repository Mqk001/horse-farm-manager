import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { PrismaClient } from '@prisma/local-client';
import bcrypt from 'bcryptjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH ?? 'playwright');
const url = process.env.TEST_DATABASE_URL;
const base = process.env.TEST_BASE_URL ?? 'http://127.0.0.1:3188';
assert.ok(url?.startsWith('file:/private/tmp/'), 'Use a disposable database');
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(base).hostname), 'Local server only');
const db = new PrismaClient({ datasources: { db: { url } } });
const suffix = Date.now();
let farm, user, browser;
try {
  farm = await db.farm.create({ data: { name: 'Optimistic test farm', code: `optimistic-${suffix}` } });
  user = await db.user.create({ data: { name: 'Optimistic Manager', email: `optimistic-${suffix}@example.test`, password: await bcrypt.hash('Optimistic-test-123', 10), emailVerifiedAt: new Date() } });
  const member = await db.farmMember.create({ data: { farmId: farm.id, userId: user.id, role: 'MANAGER' } });
  const horse = await db.horse.create({ data: { farmId: farm.id, name: 'Optimistic Thunder', status: 'ACTIVE' } });
  const care = await db.vetItem.create({ data: { horseId: horse.id, itemName: 'Optimistic vaccine', itemType: 'OTHER', nextDueDate: new Date(), assignedMemberId: member.id } });
  const task = await db.farmTask.create({ data: { farmId: farm.id, title: 'Optimistic sweep aisle', assignedMemberId: member.id } });
  const unassign = await db.farmTask.create({ data: { farmId: farm.id, title: 'Optimistic refill hay', assignedMemberId: member.id } });
  const reviewed = await db.farmTask.create({ data: { farmId: farm.id, title: 'Optimistic completed work', completedAt: new Date(), completedByName: 'Fixture' } });
  browser = await chromium.launch({ headless: true, ...(process.env.TEST_CHROME_PATH ? { executablePath: process.env.TEST_CHROME_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const response = await context.request.post(base + '/api/auth/login', { headers: { origin: base }, data: { email: user.email, password: 'Optimistic-test-123' } });
  assert.equal(response.status(), 200);
  await context.addCookies([{ name: 'reinwell_farm', value: farm.id, url: base }]);
  const page = await context.newPage();
  const { expect } = require(process.env.PLAYWRIGHT_MODULE_PATH ? process.env.PLAYWRIGHT_MODULE_PATH + '/test' : '@playwright/test');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  async function gate(fail = false) {
    let release;
    const wait = new Promise(resolve => { release = resolve; });
    let posts = 0;
    const handler = async route => {
      if (route.request().method() !== 'POST' || !route.request().headers()['next-action'] && !route.request().url().endsWith('/api/tasks/complete')) return route.continue();
      posts++;
      await wait;
      if (fail) await route.fulfill({ status: 500, contentType: 'text/plain', body: 'Simulated server rejection' });
      else await route.continue();
    };
    await page.route('**/*', handler);
    return { release, posts: () => posts, stop: () => page.unroute('**/*', handler) };
  }
  await page.goto(base + '/dashboard');
  const completeCare = page.getByRole('button', { name: 'Complete Optimistic vaccine for Optimistic Thunder', exact: true });
  await expect(completeCare.first()).toBeEnabled();
  const copies = await completeCare.count();
  assert.ok(copies >= 2, 'Fixture appears in multiple dashboard regions');
  let held = await gate(true);
  await completeCare.first().click();
  await expect(page.locator('[data-optimistic-pending="true"]')).toHaveCount(copies);
  await expect(page.getByText('Optimistic Thunder · Optimistic vaccine · Saving completion…', { exact: true }).first()).toBeVisible();
  assert.equal(await db.careCompletion.count({ where: { careItemId: care.id } }), 0);
  held.release();
  await expect(page.locator('form [role="alert"]')).toContainText('Previous view restored');
  await expect(completeCare.first()).toBeEnabled();
  await expect(page.locator('[data-optimistic-pending="true"]')).toHaveCount(0);
  assert.equal(held.posts(), 1);
  await held.stop();
  held = await gate();
  await completeCare.first().click();
  await expect(page.locator('[data-optimistic-pending="true"]')).toHaveCount(copies);
  held.release();
  await expect(completeCare).toHaveCount(0);
  await expect.poll(() => db.careCompletion.count({ where: { careItemId: care.id } })).toBe(1);
  await expect(page.locator('[data-optimistic-pending="true"]')).toHaveCount(0);
  await held.stop();

  held = await gate();
  await page.getByRole('button', { name: 'Complete Optimistic sweep aisle', exact: true }).click();
  await expect(page.getByText('Optimistic sweep aisle · Saving completion…', { exact: true })).toBeVisible();
  assert.equal((await db.farmTask.findUnique({ where: { id: task.id } })).completedAt, null);
  held.release();
  await expect(page.getByRole('button', { name: 'Complete Optimistic sweep aisle', exact: true })).toHaveCount(0);
  await expect.poll(async () => Boolean((await db.farmTask.findUnique({ where: { id: task.id } })).completedAt)).toBe(true);
  await expect(page.locator('[data-optimistic-pending="true"]')).toHaveCount(0);
  await held.stop();

  await page.goto(base + '/team');
  const memberRow = page.locator('li').filter({ has: page.getByText(user.email, { exact: true }) }).first();
  await memberRow.getByText('Assigned work', { exact: false }).click();
  const hayRow = page.locator('li').filter({ has: page.getByText('Optimistic refill hay', { exact: true }) }).last();
  held = await gate(true);
  await hayRow.getByRole('button', { name: 'Unassign', exact: true }).click();
  await expect(page.getByText('Optimistic refill hay · Unassigning…', { exact: true })).toBeVisible();
  held.release();
  await expect(hayRow.getByRole('alert')).toContainText('Previous view restored');
  await expect(hayRow.getByRole('button', { name: 'Unassign', exact: true })).toBeEnabled();
  assert.equal((await db.farmTask.findUnique({ where: { id: unassign.id } })).assignedMemberId, member.id);
  await held.stop();
  held = await gate();
  await hayRow.getByRole('button', { name: 'Unassign', exact: true }).click();
  await expect(page.getByText('Optimistic refill hay · Unassigning…', { exact: true })).toBeVisible();
  held.release();
  await expect(page.getByRole('heading', { name: 'Unassigned farm tasks' })).toBeVisible();
  assert.equal((await db.farmTask.findUnique({ where: { id: unassign.id } })).assignedMemberId, null);
  await held.stop();

  const dismiss = page.getByRole('button', { name: 'Dismiss Optimistic completed work', exact: true });
  held = await gate(true);
  await dismiss.click();
  await expect(page.getByText('Optimistic completed work · Dismissing…', { exact: true })).toBeVisible();
  held.release();
  await expect(page.locator('form [role="alert"]')).toContainText('Previous view restored');
  await expect(dismiss).toBeEnabled();
  assert.equal((await db.farmTask.findUnique({ where: { id: reviewed.id } })).dismissedAt, null);
  await held.stop();
  held = await gate();
  await dismiss.click();
  await expect(page.getByText('Optimistic completed work · Dismissing…', { exact: true })).toBeVisible();
  held.release();
  await expect(dismiss).toHaveCount(0);
  await expect.poll(async () => Boolean((await db.farmTask.findUnique({ where: { id: reviewed.id } })).dismissedAt)).toBe(true);
  await expect(page.locator('[data-optimistic-pending="true"]')).toHaveCount(0);
  await held.stop();
  assert.deepEqual(errors, []);
  console.log('PASS: immediate state before server delivery; duplicate task views synchronized; completion/unassignment/dismissal success persists; rejection visibly restores rows and controls; no browser errors.');
} finally {
  await browser?.close();
  if (farm) await db.farm.delete({ where: { id: farm.id } });
  if (user) await db.user.delete({ where: { id: user.id } });
  await db.$disconnect();
}
