import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { PrismaClient } from '@prisma/local-client';
import bcrypt from 'bcryptjs';
const require = createRequire(import.meta.url), path = process.env.PLAYWRIGHT_MODULE_PATH ?? 'playwright';
const { chromium } = require(path), { expect } = require(path + '/test');
const base = process.env.TEST_BASE_URL ?? 'http://127.0.0.1:3188';
assert.ok(['localhost', '127.0.0.1'].includes(new URL(base).hostname));
assert.ok(process.env.TEST_DATABASE_URL?.startsWith('file:/private/tmp/'));
const db = new PrismaClient({ datasources: { db: { url: process.env.TEST_DATABASE_URL } } });
let browser, user;
const farms = [];
try {
  const suffix = Date.now();
  for (const label of ['Search fixture', 'Foreign search fixture']) farms.push(await db.farm.create({ data: { name: label, code: `search-${suffix}-${farms.length}` } }));
  user = await db.user.create({ data: { name: 'Search Manager', email: `search-${suffix}@example.test`, emailVerifiedAt: new Date(), password: await bcrypt.hash('Search-test-123', 10) } });
  await db.farmMember.create({ data: { farmId: farms[0].id, userId: user.id, role: 'MANAGER' } });
  const thunder = await db.horse.create({ data: { farmId: farms[0].id, name: 'Thunder', breed: 'Thoroughbred' } });
  await db.horse.create({ data: { farmId: farms[0].id, name: 'Bella', breed: 'Quarter Horse' } });
  await db.horse.create({ data: { farmId: farms[1].id, name: 'Secret foreign horse' } });
  browser = await chromium.launch({ headless: true, ...(process.env.TEST_CHROME_PATH ? { executablePath: process.env.TEST_CHROME_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  assert.equal((await context.request.post(base + '/api/auth/login', { headers: { origin: base }, data: { email: user.email, password: 'Search-test-123' } })).status(), 200);
  await context.addCookies([{ name: 'reinwell_farm', value: farms[0].id, url: base }]);
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/horses');
  await expect(page.locator('[data-horse-result]')).toHaveCount(2);
  await page.locator('h1').click(); await page.keyboard.press('/');
  const input = page.getByRole('searchbox', { name: /Search horses/ });
  await expect(input).toBeFocused();
  let release;
  const held = new Promise(resolve => { release = resolve; });
  let searches = 0;
  const handler = async route => {
    const url = new URL(route.request().url());
    if (url.pathname === '/horses' && url.searchParams.get('q') === 'Thudner') { searches++; await held; }
    await route.continue();
  };
  await page.route('**/*', handler);
  await input.pressSequentially('Thudner', { delay: 25 });
  await expect(page.locator('#horse-search-status')).toContainText('Searching');
  assert.equal(searches, 1, 'Debounced typing performs one search request');
  release();
  await expect(page.locator('[data-horse-result]')).toHaveCount(1);
  await expect(page.locator('[data-horse-result] mark').first()).toHaveText('Thunder');
  await input.press('Escape');
  const result = page.locator('[data-horse-result]').first();
  await result.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Thunder', exact: true, level: 1 })).toBeVisible();
  await expect(page).toHaveURL(new RegExp(thunder.id));
  assert.ok(page.url().includes(thunder.id));
  await page.goBack();
  await expect(input).toHaveValue('Thudner');
  await input.focus(); await expect(page.getByText('Recent searches', { exact: true })).toBeVisible();
  await input.press('ArrowDown');
  await expect(page.getByRole('button', { name: 'Thudner', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await input.fill('zzzzzzzz');
  await expect(page.getByRole('heading', { name: 'No matching horses' })).toBeVisible();
  await expect(page.getByText('Try a shorter name, a breed, or clear the status and care filters.')).toBeVisible();
  await input.fill('Secret');
  await expect(page).toHaveURL(/q=Secret/);
  await expect(page.locator('#horse-search-status')).not.toContainText('Searching');
  await expect(page.locator('[data-horse-result]')).toHaveCount(0);
  await page.getByRole('link', { name: 'Clear filters', exact: true }).click();
  await expect(page.locator('[data-horse-result]')).toHaveCount(2);
  await expect(input).toHaveValue('');
  assert.deepEqual(errors, []);
  console.log('PASS: shortcut, debounced single request/loading, typo match/highlight, keyboard result opening, back navigation, scoped recents, empty guidance, foreign-farm exclusion and clear filters');
} finally {
  await browser?.close();
  for (const farm of farms) await db.farm.delete({ where: { id: farm.id } });
  if (user) await db.user.delete({ where: { id: user.id } });
  await db.$disconnect();
}
